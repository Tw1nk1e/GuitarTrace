"""Audit existing comparisons and current coordinates. No ML or algorithm edits.

uv run --no-sync python scripts/audit_fretboard_difference.py
"""

import copy
import csv
import hashlib
import html
import json
import re
import xml.etree.ElementTree as ET
from unittest.mock import patch

import cv2
import numpy as np

from debug_fretboard import ROOT, geometry, load_image, no_ml, save, tr
from gbcv.orient import orient_and_split

DEST = ROOT / "out" / "fretboard-difference-audit"
NUM = r"[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def elements(text):
    return list(ET.fromstring(text))


def same(a, b):
    return a.tag == b.tag and a.attrib == b.attrib


def stats(delta):
    lengths = np.linalg.norm(np.asarray(delta).reshape(-1, 2), axis=1)
    return {"max_px": float(lengths.max()), "mean_px": float(lengths.mean()),
            "points": len(lengths), "changed_points_gt_1e-8": int((lengths > 1e-8).sum())}


def path_points(element):
    assert re.sub(NUM, "", element.attrib["d"]).replace(" ", "").strip("MLZ") == ""
    return np.array([float(x) for x in re.findall(NUM, element.attrib["d"])]).reshape(-1, 2)


def render(old, new, background, lo, hi, scale, title):
    """Subpixel vector drawing at final zoom, NOT an enlarged 1px raster.

    Red-only = old, cyan-only = new, overlap = dark. Independent layers avoid
    hiding old lines beneath new lines when their centres coincide.
    """
    lo, hi = np.asarray(lo, int), np.asarray(hi, int)
    width, height = (hi - lo) * scale
    bg = cv2.resize(background[lo[1]:hi[1], lo[0]:hi[0]], (width, height))
    bg = (bg.astype(float) * .45 + 255 * .55).astype(np.uint8)
    layers = []
    for lines in (old, new):
        mask = np.zeros((height, width), np.uint8)
        for line in lines:
            p = np.round((line - lo) * scale * 256).astype(np.int32)
            cv2.polylines(mask, [p], False, 255, 2, cv2.LINE_AA, shift=8)
        layers.append(mask.astype(float) / 255)
    a, b = layers
    overlap = np.minimum(a, b)
    for weight, colour in ((a - overlap, (235, 35, 45)),
                           (b - overlap, (0, 190, 235)),
                           (overlap, (25, 25, 25))):
        bg = (bg * (1 - weight[..., None]) + np.array(colour) * weight[..., None]).astype(np.uint8)
    bg = cv2.copyMakeBorder(bg, 55, 0, 0, 0, cv2.BORDER_CONSTANT, value=(255, 255, 255))
    cv2.putText(bg, title, (10, 20), cv2.FONT_HERSHEY_SIMPLEX, .5, (25, 25, 25), 1, cv2.LINE_AA)
    cv2.putText(bg, f"RED old | CYAN new | DARK overlap | {scale}x source pixels; 2px display strokes",
                (10, 43), cv2.FONT_HERSHEY_SIMPLEX, .44, (25, 25, 25), 1, cv2.LINE_AA)
    return bg


def main():
    DEST.mkdir(exist_ok=True)
    results, sections = {}, []
    # Fail closed even if a future change unexpectedly reaches a model path.
    with patch("gbcv.segment.probability", no_ml), patch("gbcv.sam.Session", no_ml):
        for name in ("fender_1", "ibanez_rgms8"):
            folder = DEST / name
            folder.mkdir(exist_ok=True)
            source = next((ROOT / "samples" / "dl").glob(name + ".*"))
            rgba = load_image(source, mode="RGBA")
            cached = cv2.imread(str(ROOT / "out" / name / "mask.png"), 0)
            old = geometry(rgba, cached)
            new = copy.deepcopy(old)
            with patch.object(tr.fretboard, "detect", wraps=tr.fretboard.detect) as spy:
                tr.photo_board(new)
            assert spy.call_count == 1
            assert new.board_detection.accepted
            assert not np.shares_memory(new.board, old.board)
            frame, _, _ = orient_and_split(tr.silhouette(rgba), open_body=False)
            inverse = cv2.invertAffineTransform(frame.M)

            def original(points):
                return np.asarray(points) @ inverse[:, :2].T + inverse[:, 2]

            # Current comparator writes its SVGs anew; compare regenerated bytes
            # with its saved artifacts without overwriting those artifacts.
            fresh = [tr.svg(t) for t in (old, new)]
            cache_checks = {}
            for label, text in zip(("old", "new"), fresh):
                previous = (ROOT / "out" / "fretboard-edges" / name / f"{label}.svg").read_text(encoding="utf-8")
                cache_checks[label + "_fresh_equals_comparator_saved"] = previous == text
            assert all(cache_checks.values())

            # The earlier full validation predates the headstock fix. Verify
            # its BOARD prefix against live geometry, not its historical head
            # outline/bounds. Each old/new pair must still preserve its own
            # outline, hardware and bounds during a board-only correction.
            raw_full = [(ROOT / "out" / "validation-fretboard" / name / f"{label}.svg").read_bytes()
                        for label in ("old", "new")]
            full = [data.decode("utf-8").replace("\r\n", "\n") for data in raw_full]
            parsed = [elements(text) for text in full]
            prefix_sizes = [1 + len(tr.board_sides(t)) + 2 + len(t.frets) for t in (old, new)]
            assert prefix_sizes[0] == prefix_sizes[1]
            n = prefix_sizes[0]
            for text, elems in zip(fresh, parsed):
                assert all(same(a, b) for a, b in zip(elements(text)[1:n], elems[1:n]))
            assert ET.fromstring(fresh[0]).attrib["viewBox"] == ET.fromstring(fresh[1]).attrib["viewBox"]
            assert ET.fromstring(full[0]).attrib["viewBox"] == ET.fromstring(full[1]).attrib["viewBox"]
            assert same(elements(fresh[0])[0], elements(fresh[1])[0])
            assert all(same(a, b) for a, b in zip(elements(fresh[0])[n:], elements(fresh[1])[n:]))
            cache_checks["current_outline_equals_historical_snapshot"] = same(elements(fresh[0])[0], parsed[0][0])
            assert len(parsed[0]) == len(parsed[1])
            assert all(same(a, b) for a, b in zip(parsed[0][n:], parsed[1][n:]))
            original_svg = (ROOT / "out" / name / "trace.svg").read_text(encoding="utf-8")
            cache_checks["full_old_equals_original_trace_svg"] = original_svg == full[0]
            cache_checks["full_old_byte_equals_original_trace_svg"] = (ROOT / "out" / name / "trace.svg").read_bytes() == raw_full[0]
            changes = [i for i, (a, b) in enumerate(zip(*parsed)) if not same(a, b)]
            assert changes and 0 not in changes
            for label, data in zip(("old", "new"), raw_full):
                (folder / f"{label}.svg").write_bytes(data)

            boards = [t.ruler.to_px(t.board) for t in (old, new)]
            frets = [np.array([t.ruler.to_px(q) for q in tr.fret_segments(t)]) for t in (old, new)]
            rows = []

            def record(kind, index, a, b):
                oa, ob = original(a), original(b)
                for j, (p, q, s, t) in enumerate(zip(a, b, oa, ob)):
                    rows.append([kind, index, j, *p, *q, *s, *t, *list(t - s), float(np.linalg.norm(t - s))])

            record("board", 0, *boards)
            for i, (a, b) in enumerate(zip(*frets), 1):
                record("fret", i, a, b)
            with (folder / "coordinates.csv").open("w", encoding="utf-8-sig", newline="") as f:
                writer = csv.writer(f)
                writer.writerow(["kind", "index", "endpoint", "old_canvas_x", "old_canvas_y", "new_canvas_x", "new_canvas_y",
                                 "old_source_x", "old_source_y", "new_source_x", "new_source_y", "source_dx", "source_dy", "shift_px"])
                writer.writerows(rows)

            # Uniform corresponding samples, 101 on each of the four straight
            # sides. Not a ground-truth error or nearest-contour distance.
            u = np.linspace(0, 1, 101)[:, None]
            contours = [np.array([b[i] * (1 - u) + b[(i + 1) % 4] * u for i in range(4)]) for b in boards]
            side_metrics = {}
            for i, label in enumerate(("upper", "body_end", "lower", "nut")):
                side_metrics[label] = stats(original(contours[1][i]) - original(contours[0][i]))
            direction = frets[0][:, 1] - frets[0][:, 0]
            shift = frets[1] - frets[0]
            perpendicular = np.abs(direction[:, None, 0] * shift[:, :, 1] - direction[:, None, 1] * shift[:, :, 0]) / np.linalg.norm(direction, axis=1)[:, None]
            length_change = np.linalg.norm(frets[1][:, 1] - frets[1][:, 0], axis=1) - np.linalg.norm(direction, axis=1)
            endpoint_edge_distances = {}
            for label, board, lines in zip(("old", "new"), boards, frets):
                for side, indices in enumerate(((0, 1), (3, 2))):
                    a, b = board[list(indices)]
                    v = b - a
                    q = lines[:, side] - a
                    dist = np.abs(v[0] * q[:, 1] - v[1] * q[:, 0]) / np.linalg.norm(v)
                    endpoint_edge_distances[f"{label}_{'upper' if side == 0 else 'lower'}"] = {"max_px": float(dist.max()), "mean_px": float(dist.mean())}

            # Measure the actual rounded SVG M/L coordinates, not just in-memory
            # coordinates. These include nut/end and all exported fret endpoints.
            drawn = [[old.ruler.to_px(path_points(e)) for e in elems[1:n]] for elems in parsed]
            svg_delta = np.vstack(drawn[1]) - np.vstack(drawn[0])
            rounding = []
            for board, lines, exported in zip(boards, frets, drawn):
                expected = np.vstack([board[[1, 2]], board[[0, 3]], lines.reshape(-1, 2)])
                rounding.append(stats(np.vstack(exported) - expected))
            vb = [float(x) for x in ET.fromstring(full[0]).attrib["viewBox"].split()]
            styles = {}
            # True local transverse photo pixels per drawing unit (the ruler may
            # be projective, so a single d is not a globally valid conversion).
            centres = np.mean(frets[0], axis=1)
            mm = old.ruler.to_mm(centres)
            factor = np.linalg.norm(old.ruler.to_px(mm + [0, 1]) - centres, axis=1)
            for style, widths in tr.STYLES.items():
                styles[style] = {key + "_source_px_range": [float((factor * w).min()), float((factor * w).max())]
                                 for key, w in widths.items()}

            # Show exactly the lines exported by SVG, then the separate complete
            # board polygon (which the export intentionally does not always draw).
            photo = tr.masked_photo(old)
            lo = np.floor(np.vstack(boards).min(0) - [12, 12]).astype(int).clip(0)
            hi = np.minimum(np.ceil(np.vstack(boards).max(0) + [12, 12]).astype(int), photo.shape[1::-1])
            save(folder / "difference.png", render(*drawn, photo, lo, hi, 2, name + ": ACTUAL exported board/fret lines"))
            rings = [[np.vstack([b, b[:1]])] for b in boards]
            save(folder / "polygon-difference.png", render(*rings, photo, lo, hi, 2, name + ": COMPLETE polygon; sides may be suppressed in export"))
            displacements = np.linalg.norm(np.vstack([boards[1] - boards[0], shift.reshape(-1, 2)]), axis=1)
            # Most changed board corner, most changed fret endpoint, and a
            # middle-fret centre where the supporting line should coincide.
            points = [boards[0][np.argmax(displacements[:4])],
                      frets[0].reshape(-1, 2)[np.argmax(displacements[4:])],
                      frets[0][len(frets[0]) // 2].mean(0)]
            titles = ["max board corner", "max fret endpoint", "middle fret: supporting lines coincide"]
            if length_change.min() < 0:
                idx = np.argmin(length_change)
                endpoint = np.argmax(np.linalg.norm(shift[idx], axis=1))
                points.append(frets[0][idx, endpoint])
                titles.append(f"fret {idx + 1}: shortening (RED tail is old only)")
            zooms = []
            for p, title in zip(points, titles):
                a = (np.floor(p).astype(int) - [30, 18]).clip(0)
                b = np.minimum(a + [60, 36], photo.shape[1::-1])
                zooms.append(render(*drawn, photo, a, b, 12, title))
            save(folder / "zooms.png", np.vstack(zooms))
            # Native, uncached vector overlay at photo coordinates. Coincident
            # strokes multiply to dark instead of letting cyan hide red.
            paths = []
            for lines, colour in zip(drawn, ("#ed2330", "#00beeB")):
                for line in lines:
                    data = "M" + " L".join(f"{x:.6f} {y:.6f}" for x, y in line)
                    paths.append(f'<path d="{data}" fill="none" stroke="{colour}" stroke-width="0.3" style="mix-blend-mode:multiply"/>')
            svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{lo[0]} {lo[1]} {hi[0]-lo[0]} {hi[1]-lo[1]}" style="background:white;isolation:isolate">' + "".join(paths) + "</svg>"
            (folder / "difference.svg").write_text(svg, encoding="utf-8")

            result = {"accepted": new.board_detection.accepted, "confidence_not_probability": new.board_detection.confidence,
                      "cache_checks": cache_checks, "detector_calls": spy.call_count,
                      "old_sha256": sha(raw_full[0]), "new_sha256": sha(raw_full[1]),
                      "svg_elements": len(parsed[0]), "changed_svg_elements": len(changes), "changed_indices_zero_based": changes,
                      "full_board_prefix_verified_against_current_geometry": True,
                      "all_hardware_and_outline_unchanged": True,
                      "visible_long_board_sides_old_new": [len(tr.board_sides(t)) for t in (old, new)],
                      "frets": len(old.frets), "changed_fret_endpoints": int((np.linalg.norm(shift, axis=2) > 1e-8).sum()),
                      "board_vertices": stats(original(boards[1]) - original(boards[0])),
                      "fret_endpoints": stats(shift), "all_board_and_fret_endpoints": stats(np.vstack([boards[1]-boards[0], shift.reshape(-1, 2)])),
                      "contour_404_corresponding_samples": stats((contours[1] - contours[0]).reshape(-1, 2)),
                      "boundary_samples": side_metrics, "rounded_export_svg_endpoints": stats(svg_delta),
                      "svg_coordinate_rounding_error_old_new": rounding,
                      "fret_endpoint_distance_to_polygon_sides": endpoint_edge_distances,
                      "max_perpendicular_fret_support_line_shift_px": float(perpendicular.max()),
                      "fret_length_change_px_range": [float(length_change.min()), float(length_change.max())],
                      "ruler_c": old.ruler.ff.c, "frame_rotation_scale_singular_values": np.linalg.svd(frame.M[:, :2])[1].tolist(),
                      "source_size_wh": list(rgba.shape[1::-1]), "canvas_size_wh": list(photo.shape[1::-1]),
                      "stroke_widths": styles,
                      "at_160px_svg_height": {"fret_stroke_png_px": tr.STYLES["png"]["thin"] * 160 / vb[3],
                                                "max_rounded_endpoint_shift_px": float(np.linalg.norm(np.vstack([path_points(e) for e in parsed[1][1:n]]) - np.vstack([path_points(e) for e in parsed[0][1:n]]), axis=1).max() * 160 / vb[3])},
                      "ml_executed": False, "ground_truth_accuracy_measured": False}
            results[name] = result
            print(name, json.dumps(result, ensure_ascii=False))
            sections.append(f'<h2>{html.escape(name)}</h2><p>Красный — старое, голубой — новое, тёмный — совпадение. Растр: независимые субпиксельные слои, линии 2 экранных px. Увеличение не растягивает исходный растр.</p><a href="{name}/coordinates.csv">Все координаты в исходных пикселях</a><p>Реальные экспортируемые линии:</p><img src="{name}/difference.png"><p>Увеличения ×12:</p><img src="{name}/zooms.png"><p>Полный полигон (диагностика, не видимый контур экспорта):</p><img src="{name}/polygon-difference.png"><p>Нативная векторная разница, тонкие линии:</p><object data="{name}/difference.svg" type="image/svg+xml"></object><p>Исходные полные SVG, единый viewBox, без собственной растеризации:</p><div class="pair"><object data="{name}/old.svg" type="image/svg+xml"></object><object data="{name}/new.svg" type="image/svg+xml"></object></div>')
    (DEST / "metrics.json").write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")
    (DEST / "index.html").write_text('<!doctype html><meta charset="utf-8"><title>Разница геометрии накладки</title><style>body{font:16px sans-serif;margin:24px;background:#fafafa}img{display:block;max-width:none;margin:12px 0}object{width:100%;height:350px;background:white}.pair{display:grid;grid-template-columns:1fr 1fr;gap:12px}</style><h1>Аудит: старое / новое, без ML</h1><p>Масштаб растров указан в заголовках; прокручивайте по горизонтали, браузер не уменьшает их автоматически. Фото только внутри маски гитары. Числа — изменения, не ошибка относительно эталона.</p><a href="metrics.json">Измерения и SHA-256</a>' + "".join(sections), encoding="utf-8")


if __name__ == "__main__":
    main()
